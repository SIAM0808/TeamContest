using ll = long long;
long long binexp(long long a, long long b, long long mod) {
    long long res = 1;
    a %= mod;
    while (b) {
        if (b & 1) res = res * a % mod;
        a = a * a % mod;
        b >>= 1;
    }
    return res;
}
void Solve()
{
    ll n, k, mod;
    cin >> n >> k >> mod;
    ll ans = 0;
    ll mul = (k * (binexp(n, k-1, mod))) % mod;
    for(ll i=0; i<n; i++){
        ll x;
        cin >> x;
        ans = (ans + (mul * x)) % mod;
    }
    cout << ans << endl;
}

int32_t main()
{
    ios_base::sync_with_stdio(0), cin.tie(0), cout.tie(0);
    ll t = 1;
    cin >> t;
    for (ll i = 1; i <= t; i++)
    {
        cout << "Case " << i << ": ";
        Solve();
    }
    return 0;
}