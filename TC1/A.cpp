using ll = long long;

void Solve()
{
    int n, k;
    cin >> n >> k;
    if(k == 2*n) cout << 2*n << endl;
    else if(k > n) cout << (k%n) * 2 << endl;
    else cout << 0 << endl;
}

int32_t main()
{
    ios_base::sync_with_stdio(0), cin.tie(0), cout.tie(0);
    ll t = 1;
    cin >> t;
    while (t--)
        Solve();
    return 0;
}